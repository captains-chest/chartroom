import { defineConfig } from 'vite-plus';
import { readFileSync } from 'node:fs';
import { minifyLiterals } from './scripts/minify-literals';

const { version } = JSON.parse(readFileSync('package.json', 'utf8')) as { version: string };

// Entry modules served by the integration from /chartroom_static/<version>/. File names carry no
// hash: the version in the path busts caches (companion apps included) for every file, chunks and
// the worker too, and the build embeds it so an open tab can tell it is out of date.
export default defineConfig({
  base: './',
  define: { __CHARTROOM_VERSION__: JSON.stringify(version) },
  publicDir: false,
  plugins: [minifyLiterals()],
  build: {
    outDir: 'custom_components/chartroom/frontend',
    emptyOutDir: true,
    target: 'es2022',
    modulePreload: false,
    reportCompressedSize: true,
    rollupOptions: {
      input: {
        'chartroom-panel': 'frontend/src/chartroom-panel.ts',
        'chartroom-card': 'frontend/src/chartroom-card.ts',
        // The field worker is an entry too, so it shares chunks with the in-page fallback
        // (field-worker.ts) instead of shipping the field code twice.
        'workers/worker': 'frontend/src/worker.ts',
      },
      output: {
        entryFileNames: '[name].js',
        // Lazy chunks keep their module's name; the code shared by the panel and the card has a
        // stable one (the size check counts it towards the card).
        chunkFileNames: (c) => (c.isDynamicEntry ? 'chunks/[name].js' : 'chunks/shared.js'),
        assetFileNames: 'assets/[name][extname]',
      },
    },
  },
  test: {
    include: ['frontend/test/**/*.test.ts'],
    environment: 'node',
  },
  lint: {
    ignorePatterns: [
      'custom_components/chartroom/frontend/**',
      'test-results/**',
      'playwright-report/**',
    ],
    jsPlugins: [{ name: 'vite-plus', specifier: 'vite-plus/oxlint-plugin' }],
    rules: { 'vite-plus/prefer-vite-plus-imports': 'error' },
    options: { typeAware: true, typeCheck: true },
  },
  fmt: {
    printWidth: 100,
    singleQuote: true,
    sortPackageJson: false,
    ignorePatterns: [
      'pnpm-lock.yaml',
      'custom_components/chartroom/frontend/',
      // Generated by scripts/example-plan/trace.mjs; CI checks it is reproducible.
      'frontend/test/fixtures/example-plan.json',
      'node_modules/',
      'test-results/',
      'playwright-report/',
    ],
  },
});
